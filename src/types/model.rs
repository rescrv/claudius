impl FromStr for Model {
    type Err = ();

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match KnownModel::from_str(s) {
            Ok(known_model) => Ok(Model::Known(known_model)),
            Err(_) => Ok(Model::Custom(s.to_string())),
        }
    }
}

